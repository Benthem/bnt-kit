#!/usr/bin/env node
// Bundles migrations/*.sql (NNNN_name.sql) into a TypeScript module the Worker
// imports, so it can apply them itself (bnt-kit/d1-migrations).
//   bnt-bundle-migrations <migrations dir> <output .ts> [--check]
// --check (for npm run check) fails when the output is stale.
import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const [dirArg, outArg] = process.argv.slice(2).filter((a) => !a.startsWith("--"));
if (!dirArg || !outArg) {
  console.error("usage: bnt-bundle-migrations <migrations dir> <output .ts> [--check]");
  process.exit(2);
}
const dir = resolve(dirArg);
const out = resolve(outArg);
const names = (await readdir(dir)).filter((name) => /^\d{4}_.+\.sql$/.test(name)).sort();
const files = await Promise.all(names.map(async (name) => ({ name, sql: await readFile(`${dir}/${name}`, "utf8") })));
const source = `// Generated by bnt-bundle-migrations from ${dirArg}/*.sql. Do not edit.
export const MIGRATIONS: readonly { name: string; sql: string }[] = ${JSON.stringify(files, null, 2)};
`;
if (process.argv.includes("--check")) {
  const current = await readFile(out, "utf8").catch(() => "");
  if (current !== source) {
    console.error(`${outArg} is out of date: run \`npm run migrations\`.`);
    process.exit(1);
  }
} else {
  await writeFile(out, source);
  console.log(`Bundled ${files.length} migrations.`);
}
